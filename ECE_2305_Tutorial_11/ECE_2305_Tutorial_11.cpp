#include<iostream> 
using namespace std;

int main()
{
	int a;

	cout << "Enter a" << endl;
	cin >> a;

	if (a < 5) {
		cout << "a < 5" << endl;
	}
	if (a < 10) {
		cout << "a < 10" << endl;
	}
	if (a < 15) {
		cout << "a < 15" << endl;
	}
	if (a < 20) {
		cout << "a < 20" << endl;
	}

	system("pause");
	return 0;
}
